// WCAG 2.2 and APCA contrast report for every required token pair in every brand and mode.
// Writes docs/contrast-report.md and exits 1 if any pair misses WCAG 2.2 AA.
// Run: pnpm contrast
import { readFileSync, writeFileSync } from "node:fs";
import { brands, modes, tokens } from "@leeward/tokens";
import { checkPairs, type PairResult } from "@leeward/tokens/contrast";

const adjustments = JSON.parse(readFileSync(new URL("../packages/tokens/dist/adjustments.json", import.meta.url), "utf8")) as Record<string, Array<{ token: string; ramp: string; from: string; to: string; reason: string }>>;

export function checkTheme(brand: (typeof brands)[number], mode: (typeof modes)[number]): PairResult[] {
  const map = tokens[brand][mode] as Record<string, { value: unknown }>;
  return checkPairs(`${brand} ${mode}`, (name) => (map[name] ? String(map[name]!.value) : undefined));
}

function report(results: PairResult[]): string {
  const failures = results.filter((r) => !r.pass);
  const lines = [
    "# Contrast report",
    "",
    "Generated by `scripts/contrast-report.ts`. Do not edit by hand.",
    "",
    `- Brands and modes: ${brands.flatMap((b) => modes.map((m) => `${b} ${m}`)).join(", ")}`,
    `- Pairs checked: ${results.length}`,
    `- WCAG 2.2 AA failures: ${failures.length}`,
    `- Below APCA guidance (informational): ${results.filter((r) => !r.apcaOk).length}`,
    "",
    "Pass bar: WCAG 2.2 AA. Text needs 4.5:1. UI parts, icons and large text need 3:1.",
    "",
    "## What the resolver changed",
    "",
    "The semantic mapping starts from Leeward's semantic template. Where a pair missed AA, the resolver moved the token one ramp step at a time until it passed.",
    "",
  ];
  for (const [theme, list] of Object.entries(adjustments)) {
    const final = new Map<string, { ramp: string; from: string; to: string; reason: string }>();
    for (const a of list) final.set(a.token, { ...a, from: final.get(a.token)?.from ?? a.from });
    lines.push(`### ${theme}`, "", "| Token | Ramp | Template step | Final step | First reason |", "|---|---|---|---|---|");
    for (const [token, a] of final) lines.push(`| \`${token}\` | ${a.ramp} | ${a.from} | ${a.to} | ${a.reason} |`);
    lines.push("");
  }
  for (const brand of brands) {
    for (const mode of modes) {
      lines.push(`## ${brand} ${mode}`, "", "| Foreground | Background | Min | WCAG | APCA Lc | Result |", "|---|---|---|---|---|---|");
      for (const r of results.filter((x) => x.theme === `${brand} ${mode}`)) {
        lines.push(`| \`${r.fg}\` ${r.fgHex} | \`${r.bg}\` ${r.bgHex} | ${r.min}:1 | ${r.wcag.toFixed(2)}:1 | ${r.apca.toFixed(1)} | ${r.pass ? "Pass" : "**Fail**"} |`);
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

if (import.meta.main) {
  const results = brands.flatMap((b) => modes.map((m) => checkTheme(b, m))).flat();
  writeFileSync(new URL("../docs/contrast-report.md", import.meta.url), report(results));
  const failures = results.filter((r) => !r.pass);
  console.log(`Checked ${results.length} pairs across ${brands.length} brands in light and dark. Failures: ${failures.length}.`);
  for (const f of failures) console.error(`FAIL [${f.theme}] ${f.fg} on ${f.bg}: ${f.wcag.toFixed(2)}:1 (needs ${f.min}:1)`);
  if (failures.length > 0) process.exit(1);
}
