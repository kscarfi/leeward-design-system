// WCAG 2.2 and APCA contrast report for every required token pair in every theme.
// Writes docs/contrast-report.md and exits 1 if any pair misses WCAG 2.2 AA.
// Run: pnpm contrast
import { writeFileSync } from "node:fs";
import Color from "colorjs.io";
import { tokens, themes } from "@leeward/tokens";
import { requiredPairs, type ContrastPair } from "@leeward/tokens/themes";

const AA: Record<ContrastPair["kind"], number> = { text: 4.5, large: 3, ui: 3 };
// APCA guidance (Lc) for reference only. WCAG 2.2 AA is the pass/fail bar.
const APCA_GUIDE: Record<ContrastPair["kind"], number> = { text: 60, large: 45, ui: 30 };

export interface PairResult extends ContrastPair {
  theme: string;
  fgHex: string;
  bgHex: string;
  wcag: number;
  apca: number;
  pass: boolean;
  apcaOk: boolean;
}

function hexOf(theme: string, name: string): string {
  const entry = (tokens as Record<string, Record<string, { value: unknown }>>)[theme]?.[`color.${name}`];
  if (!entry) throw new Error(`Unknown token color.${name} in theme ${theme}`);
  return String(entry.value);
}

/** Composite a translucent color over its background before measuring. */
function opaque(fg: Color, bg: Color): Color {
  const a = fg.alpha ?? 1;
  if (a >= 1) return fg;
  const [r1, g1, b1] = fg.to("srgb").coords;
  const [r2, g2, b2] = bg.to("srgb").coords;
  return new Color("srgb", [r1! * a + r2! * (1 - a), g1! * a + g2! * (1 - a), b1! * a + b2! * (1 - a)]);
}

export function checkTheme(theme: string, pairs = requiredPairs, lookup = (name: string) => hexOf(theme, name)): PairResult[] {
  return pairs.map((pair) => {
    const bg = new Color(lookup(pair.bg));
    const fg = opaque(new Color(lookup(pair.fg)), bg);
    const wcag = fg.contrast(bg, "WCAG21");
    const apca = Math.abs(bg.contrast(fg, "APCA"));
    return {
      ...pair,
      theme,
      fgHex: lookup(pair.fg),
      bgHex: lookup(pair.bg),
      wcag,
      apca,
      pass: wcag >= AA[pair.kind],
      apcaOk: apca >= APCA_GUIDE[pair.kind],
    };
  });
}

function report(results: PairResult[]): string {
  const failures = results.filter((r) => !r.pass);
  const lines = [
    "# Contrast report",
    "",
    "Generated by `scripts/contrast-report.ts`. Do not edit by hand.",
    "",
    `- Themes: ${themes.join(", ")}`,
    `- Pairs checked: ${results.length}`,
    `- WCAG 2.2 AA failures: ${failures.length}`,
    `- Below APCA guidance (informational): ${results.filter((r) => !r.apcaOk).length}`,
    "",
    "Pass bar: WCAG 2.2 AA. Text needs 4.5:1. UI parts and large text need 3:1.",
    "APCA Lc is reported for perceptual quality. Guidance used: text 60, large 45, UI 30.",
    "",
  ];
  for (const theme of themes) {
    lines.push(`## ${theme}`, "", "| Foreground | Background | Kind | WCAG | APCA Lc | Result |", "|---|---|---|---|---|---|");
    for (const r of results.filter((x) => x.theme === theme)) {
      const result = r.pass ? (r.apcaOk ? "Pass" : "Pass (APCA low)") : "**Fail**";
      lines.push(`| \`${r.fg}\` ${r.fgHex} | \`${r.bg}\` ${r.bgHex} | ${r.kind} | ${r.wcag.toFixed(2)}:1 | ${r.apca.toFixed(1)} | ${result} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

if (import.meta.main) {
  const results = themes.flatMap((theme) => checkTheme(theme));
  writeFileSync(new URL("../docs/contrast-report.md", import.meta.url), report(results));
  const failures = results.filter((r) => !r.pass);
  console.log(`Checked ${results.length} pairs across ${themes.length} themes. Failures: ${failures.length}.`);
  for (const f of failures) console.error(`FAIL [${f.theme}] ${f.fg} on ${f.bg}: ${f.wcag.toFixed(2)}:1 (needs ${AA[f.kind]}:1)`);
  const low = results.filter((r) => r.pass && !r.apcaOk);
  for (const l of low) console.log(`APCA low [${l.theme}] ${l.fg} on ${l.bg}: Lc ${l.apca.toFixed(1)}`);
  if (failures.length > 0) process.exit(1);
}
