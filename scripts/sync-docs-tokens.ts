const px = (v: unknown) => {
  const s = String(v);
  if (s === "0") return "0";
  if (s.endsWith("rem")) return `${parseFloat(s) * 16} px`;
  if (s.endsWith("px")) return `${parseFloat(s)} px`;
  return s;
};

function section(name: string): string {
  const spec = COMPONENT_TOKENS[name]!;
  const leeward = tokens.leeward.light as Record<string, { value: unknown; cssVar: string; ref?: string }>;
  const business = tokens.business.light as typeof leeward;
  const rows = Object.keys(leeward)
    .filter((k) => spec.prefixes.some((p) => k.startsWith(p)))
    .map((k) => `| \`${leeward[k]!.cssVar}\` | ${px(leeward[k]!.value)} | ${px(business[k]!.value)} | ${leeward[k]!.ref ? `\`${leeward[k]!.ref}\`` : ""} |`);
  const lines = ["## Tokens", "", "<!-- Generated by scripts/sync-docs-tokens.ts from the compiled tokens. Do not edit this section by hand. -->", ""];
  if (spec.note) lines.push(spec.note, "");
  if (rows.length) {
    lines.push("Sizing and radius tokens. Change them in `packages/tokens/build/foundation.ts`; the component CSS reads only these.", "");
    lines.push("| CSS variable | Leeward | Leeward Business | Refers to |", "|---|---|---|---|", ...rows, "");
  }
  return lines.join("\n");
}

const check = process.argv.includes("--check");
const stale: string[] = [];
for (const name of Object.keys(COMPONENT_TOKENS)) {
  const file = `${src}${COMPONENT_TOKENS[name]!.path}/${name}.docs.md`;
  const md = readFileSync(file, "utf8");
  const body = section(name);
  const pattern = /## Tokens\n[\s\S]*?(?=\n## |$)/;
  const next = pattern.test(md) ? md.replace(pattern, body.trimEnd() + "\n") : md.replace(/\n## Accessibility\n/, `\n${body}\n## Accessibility\n`);
  if (next !== md) {
    stale.push(name);
    if (!check) writeFileSync(file, next);
  }
}
if (check && stale.length) {
  console.error(`Token sections are stale in: ${stale.join(", ")}. Run pnpm build:agent.`);
  process.exit(1);
}
console.log(check ? "Token sections are up to date." : `Updated token sections in ${stale.length} docs.`);
