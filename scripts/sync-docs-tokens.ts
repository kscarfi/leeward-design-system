// Writes the "Tokens" section of every component's Name.docs.md from the compiled tokens,
// so sizing and radius docs never drift from the real values. Run: pnpm build:agent
// With --check it only reports stale files (used in CI).
import { readFileSync, writeFileSync } from "node:fs";
import { tokens } from "@leeward/tokens";

const src = new URL("../packages/react/src/", import.meta.url).pathname;

