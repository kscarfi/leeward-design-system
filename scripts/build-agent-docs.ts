// Writes components.manifest.json, DESIGN.md and llms.txt. Run: pnpm build:agent
// Everything comes from source: component code, Name.docs.md, tokens and guidelines.
import { writeFileSync } from "node:fs";
import { brandNames, brands, tokens } from "@leeward/tokens";
import { guidelines } from "../packages/mcp-server/src/guidelines.ts";
import { buildManifest } from "./build-manifest.ts";

const root = new URL("../", import.meta.url).pathname;
const repo = "https://github.com/kscarfi/leeward-design-system";

const manifest = buildManifest();
writeFileSync(`${root}components.manifest.json`, JSON.stringify(manifest, null, 2) + "\n");

type Entry = { value: unknown; cssVar: string; description?: string };
const light = tokens.leeward.light as Record<string, Entry>;
const dark = tokens.leeward.dark as Record<string, Entry>;
// The most used color tokens. The full list (700+) is in get_tokens and the Figma files.
const KEY = /^(text\.(default|muted|subtle|placeholder|inverse|primary|link-default|success|warning|danger)|fill\.surface\.(canvas|default|raised|overlay|bold)|fill\.(primary|neutral|success|warning|danger)\.(default|on-default|weak)|border\.(default|subtle|strong|focus|danger)|amount\.\w+|fill\.accent\.default)$/;
const colorRows = Object.entries(light)
  .filter(([name]) => KEY.test(name))
  .map(([name, t]) => `| \`${t.cssVar}\` | ${String(t.value)} | ${String(dark[name]?.value ?? "")} | ${t.description ?? ""} |`);

const section = (key: string) => {
  const g = guidelines[key]!;
  return [`## ${g.title}`, "", g.summary, "", ...g.rules.map((r) => `- ${r}`), ...(g.example ? ["", "```tsx", g.example, "```"] : []), ""].join("\n");
};

const design = [
  "# DESIGN.md: Leeward Design System",
  "",
  "> Generated by `scripts/build-agent-docs.ts`. Do not edit by hand.",
  "",
  "Leeward is a fictional digital bank. This file tells people and AI agents how to build Leeward screens that are on-brand, accessible and consistent.",
  "",
  "## Read this first",
  "",
  "1. Use components from `@leeward/react`. Do not invent new ones for things listed below.",
  "2. Style only with semantic `var(--lw-*)` tokens. No hex, rgb or raw px spacing.",
  "3. Every amount goes through `AmountDisplay`. Outgoing money is never red.",
  "4. Every input has a visible label. Every icon-only button has a `label`.",
  "5. No em dashes in any copy.",
  "",
  "## Setup",
  "",
  "```tsx",
  'import "@leeward/react/fonts.css";',
  'import "@leeward/react/styles.css";',
  'import { ToastProvider, TooltipProvider } from "@leeward/react";',
  "",
  '<div data-brand="leeward" data-theme="light">',
  "  <TooltipProvider>",
  "    <ToastProvider>{app}</ToastProvider>",
  "  </TooltipProvider>",
  "</div>",
  "```",
  "",
  ...Object.keys(guidelines).map(section),
  "## Brands",
  "",
  "| Brand | data-brand | Notes |",
  "|---|---|---|",
  ...brands.map((b) => `| ${brandNames[b]} | \`${b}\` | ${b === "leeward" ? "Default. Indigo primary, slate neutrals, comfortable density." : "Lapis primary, purple haze secondary, compact density, tighter radii."} |`),
  "| Partner | your name | Generated from one color with `pnpm theme:generate`. Refused if any pair misses AA. |",
  "",
  "## Components",
  "",
  "| Component | Kind | Purpose |",
  "|---|---|---|",
  ...manifest.components.map((c) => `| \`${c.name}\` | ${c.kind} | ${c.purpose} |`),
  "",
  "Full props, rules and examples: [`components.manifest.json`](components.manifest.json).",
  "",
  "## Icons",
  "",
  manifest.icons.map((i) => `\`${i}\``).join(", "),
  "",
  "## Key color tokens (Leeward)",
  "",
  "| CSS variable | Light | Dark | Use |",
  "|---|---|---|---|",
  ...colorRows,
  "",
  "Every token: `get_tokens` in the MCP server, or `packages/tokens/dist/ts/`. Every required pair is checked against WCAG 2.2 AA in [docs/contrast-report.md](docs/contrast-report.md).",
  "",
].join("\n");
writeFileSync(`${root}DESIGN.md`, design);

const llms = [
  "# Leeward Design System",
  "",
  "> Open-source, AI-ready design system for Leeward, a fictional digital bank. React components, semantic design tokens and rules that keep generated banking screens on-brand and accessible.",
  "",
  "Use components from @leeward/react, style only with var(--lw-*) semantic tokens, render money with AmountDisplay, and never use em dashes in copy.",
  "",
  "## Docs",
  "",
  `- [DESIGN.md](${repo}/blob/main/DESIGN.md): principles, token rules, layout, copy, accessibility, component list`,
  `- [components.manifest.json](${repo}/blob/main/components.manifest.json): every component with props, variants, do and don't rules, accessibility and an example`,
  `- [Contrast report](${repo}/blob/main/docs/contrast-report.md): WCAG 2.2 and APCA results for every token pair`,
  "",
  "## Tools",
  "",
  `- [MCP server](${repo}/tree/main/packages/mcp-server): get_tokens, get_component, search_components, get_guidelines, validate_ui`,
  `- [Tokens](${repo}/tree/main/packages/tokens/dist): CSS variables, typed TS and Figma variables`,
  "",
  "## Optional",
  "",
  `- [Decisions](${repo}/tree/main/docs/decisions): why the system is built this way`,
  `- [Build log](${repo}/blob/main/docs/build-log.md): time spent and AI mistakes`,
  "",
].join("\n");
writeFileSync(`${root}llms.txt`, llms);

console.log(`Wrote components.manifest.json (${manifest.components.length} entries), DESIGN.md (${design.split("\n").length} lines), llms.txt.`);
