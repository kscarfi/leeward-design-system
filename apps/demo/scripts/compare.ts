// Measures both runs and writes COMPARISON.md. Numbers come only from tools, never by hand.
// Run: pnpm --filter @leeward/demo compare
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { validateUi } from "@leeward/mcp-server/validate";

const root = new URL("../", import.meta.url).pathname;
const runs = [
  { id: "a-without-system", label: "A: without system" },
  { id: "b-with-system", label: "B: with system" },
];

const present = runs.filter((r) => existsSync(`${root}runs/${r.id}/TransferScreen.tsx`));
if (present.length === 0) {
  console.log("No runs yet. Follow RUNBOOK.md, then run this again.");
  process.exit(0);
}

try {
  execFileSync(`${root}node_modules/.bin/playwright`, ["test"], { cwd: root, stdio: "inherit" });
} catch {
  console.error("Rendering or axe failed for at least one run. Results below use whatever was recorded.");
}

interface Axe { rendered: boolean; errors: string[]; violations: Array<{ id: string; impact: string; nodes: number; help: string }> }

const rows = present.map((run) => {
  const code = readFileSync(`${root}runs/${run.id}/TransferScreen.tsx`, "utf8");
  const v = validateUi(code);
  const axeFile = `${root}results/${run.id}.axe.json`;
  const axe: Axe | undefined = existsSync(axeFile) ? JSON.parse(readFileSync(axeFile, "utf8")) : undefined;
  const nodes = (id?: string) => axe?.violations.filter((x) => !id || x.id === id).reduce((n, x) => n + x.nodes, 0) ?? NaN;
  return {
    run,
    metrics: {
      "Lines of code": v.stats.lines,
      "Raw colors": v.summary["raw-color"],
      "Raw spacing values": v.summary["raw-spacing"],
      "Unknown or primitive Leeward tokens": v.summary["unknown-token"] + v.summary["primitive-token"],
      "Own CSS variables defined (a private palette)": v.stats.customCssVariables.length,
      "Custom components invented": v.stats.customComponents.length,
      "Leeward components used": v.stats.leewardComponents,
      "Missing labels (static)": v.summary["missing-label"],
      "Hand-formatted money": v.summary["hand-formatted-money"],
      "Red amounts or icon-only money actions": v.summary["red-amount"] + v.summary["icon-only-money-action"],
      "Em dashes in copy": v.summary["em-dash"],
      "axe violations (rules)": axe ? axe.violations.length : NaN,
      "axe violations (elements)": nodes(),
      "Color contrast failures (axe)": nodes("color-contrast"),
      "Rendered without runtime errors": axe ? (axe.rendered && axe.errors.length === 0 ? "Yes" : "No") : "Not measured",
    } as Record<string, number | string>,
    custom: v.stats.customComponents,
    axe,
  };
});

const keys = Object.keys(rows[0]!.metrics);
const fmt = (x: number | string) => (typeof x === "number" && Number.isNaN(x) ? "n/a" : String(x));
const md = [
  "# Same prompt, two results",
  "",
  "> Generated by `apps/demo/scripts/compare.ts`. Outputs in `runs/` are unedited.",
  "",
  `| Metric | ${rows.map((r) => r.run.label).join(" | ")} |`,
  `|---|${rows.map(() => "---").join("|")}|`,
  ...keys.map((k) => `| ${k} | ${rows.map((r) => fmt(r.metrics[k]!)).join(" | ")} |`),
  "",
  "## How each number is measured",
  "",
  "- Static checks come from the same `validate_ui` function the MCP server exposes.",
  "- axe runs in Chromium on the rendered screen with WCAG 2.0, 2.1 and 2.2 A and AA rules.",
  "- Custom components are capitalized components declared in the file and not imported from Leeward.",
  "- Raw colors and raw spacing count every occurrence, including CSS written inside strings. Code comments are not counted.",
  "- Run A is shown on a plain page. Run B is shown with the app setup DESIGN.md asks for (Leeward CSS, a theme and providers). The output files are not changed.",
  "",
  ...rows.flatMap((r) => [
    `## ${r.run.label}`,
    "",
    `Custom components: ${r.custom.length ? r.custom.map((c) => `\`${c}\``).join(", ") : "none"}`,
    "",
    ...(r.axe?.violations.length ? ["| axe rule | Impact | Elements |", "|---|---|---|", ...r.axe.violations.map((x) => `| ${x.id} | ${x.impact} | ${x.nodes} |`)] : ["No axe violations recorded."]),
    "",
  ]),
].join("\n");

writeFileSync(`${root}COMPARISON.md`, md);
console.log(md);
