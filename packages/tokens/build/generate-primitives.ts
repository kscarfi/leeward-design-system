// Writes src/primitive/color.json from the seed palette. Run: pnpm --filter @leeward/tokens generate
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { generateDeepRamp, generateRamp, seedSteps } from "./palette.ts";
import { deepSeed, leewardRamps } from "./seeds.ts";

export function buildColorPrimitives(ramps = leewardRamps, deep = deepSeed) {
  const color: Record<string, unknown> = {
    $type: "color",
    white: { $value: "#ffffff" },
  };
  for (const [name, spec] of Object.entries(ramps)) {
    const ramp = generateRamp(spec);
    const pinned = new Set(seedSteps(spec));
    color[name] = Object.fromEntries(
      Object.entries(ramp).map(([step, hex]) => [
        step,
        pinned.has(Number(step) as never) ? { $value: hex, $description: "Seed color" } : { $value: hex },
      ]),
    );
  }
  color.deep = {
    $description: "Dark mode surfaces. Low chroma, tinted with the Ink hue.",
    ...Object.fromEntries(Object.entries(generateDeepRamp(deep)).map(([step, hex]) => [step, { $value: hex }])),
  };
  return {
    $description: "Generated by build/generate-primitives.ts from build/seeds.ts. Do not edit by hand.",
    color,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL("../src/primitive/color.json", import.meta.url);
  writeFileSync(out, JSON.stringify(buildColorPrimitives(), null, 2) + "\n");
  console.log("Wrote src/primitive/color.json");
}
